import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("installer", ROOT / "tools/install.py")
installer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(installer)


class InstallTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.base = Path(self.tmp.name)
        self.source = self.base / "release"
        self.source.mkdir()
        (self.source / "VERSION").write_text("0.1.0\n")
        (self.source / "SKILL.md").write_text("Initial skill.\n")
        self.dest = self.base / "skills" / "math-paper-editor"
        self.backups = self.base / "backups"

    def tearDown(self):
        self.tmp.cleanup()

    def run_install(self, apply=True, baseline=None):
        return installer.install(self.source, self.dest, self.backups, apply, baseline)

    def test_preview_writes_nothing(self):
        self.assertFalse(self.run_install(False)["applied"])
        self.assertFalse(self.dest.parent.exists())

    def test_fresh_install_and_state(self):
        self.run_install()
        state = json.loads((self.dest / installer.STATE).read_text())
        self.assertEqual(state["version"], "0.1.0")
        self.assertEqual(state["files"], installer.files_at(self.source))

    def test_upgrade_backs_up_and_retains_extras(self):
        self.run_install()
        (self.dest / "local-notes.txt").write_text("Keep me.\n")
        (self.source / "SKILL.md").write_text("New skill.\n")
        result = self.run_install()
        backup = Path(result["backup"])
        self.assertEqual((backup / "SKILL.md").read_text(), "Initial skill.\n")
        self.assertEqual((self.dest / "local-notes.txt").read_text(), "Keep me.\n")
        self.assertEqual((self.dest / "SKILL.md").read_text(), "New skill.\n")

    def test_changed_managed_file_aborts(self):
        self.run_install()
        (self.dest / "SKILL.md").write_text("User customization.\n")
        with self.assertRaises(ValueError):
            self.run_install()
        self.assertEqual((self.dest / "SKILL.md").read_text(), "User customization.\n")

    def test_unmanaged_existing_skill_requires_baseline(self):
        self.dest.mkdir(parents=True)
        (self.dest / "old.txt").write_text("Legacy.\n")
        with self.assertRaises(ValueError):
            self.run_install()
        baseline = installer.files_at(self.dest)
        result = self.run_install(baseline=baseline)
        self.assertEqual((Path(result["backup"]) / "old.txt").read_text(), "Legacy.\n")

    def test_legacy_drift_aborts(self):
        self.dest.mkdir(parents=True)
        (self.dest / "old.txt").write_text("Legacy.\n")
        baseline = installer.files_at(self.dest)
        (self.dest / "old.txt").write_text("New user work.\n")
        with self.assertRaises(ValueError):
            self.run_install(baseline=baseline)
        self.assertFalse(self.backups.exists())

    def test_unmanaged_collision_aborts(self):
        self.run_install()
        (self.dest / "new.txt").write_text("Local extra.\n")
        (self.source / "new.txt").write_text("Package file.\n")
        with self.assertRaises(ValueError):
            self.run_install()

    def test_symlink_destination_aborts(self):
        self.dest.parent.mkdir(parents=True)
        self.dest.symlink_to(self.source, target_is_directory=True)
        with self.assertRaises(ValueError):
            self.run_install()

    def test_removed_managed_file_retired_with_backup(self):
        (self.source / "old.txt").write_text("Old managed.\n")
        self.run_install()
        (self.source / "old.txt").unlink()
        result = self.run_install()
        self.assertFalse((self.dest / "old.txt").exists())
        self.assertTrue((Path(result["backup"]) / "old.txt").exists())

    def test_nested_backup_directory_rejected_before_writes(self):
        with self.assertRaises(ValueError):
            installer.install(self.source, self.dest, self.dest / "backups", True)
        self.assertFalse(self.dest.exists())

    def test_generated_python_cache_is_not_installed_or_managed(self):
        cache = self.source / "__pycache__"
        cache.mkdir()
        (cache / "example.pyc").write_bytes(b"generated bytecode")
        self.run_install()
        self.assertFalse((self.dest / "__pycache__").exists())
        state = json.loads((self.dest / installer.STATE).read_text())
        self.assertNotIn("__pycache__/example.pyc", state["files"])


if __name__ == "__main__":
    unittest.main()
